"""Build LaTeX metrics from actual immutable run records; no hard-coded performance."""

from pathlib import Path
import json
import numpy as np
import argparse
import pandas as pd
from patchloss.config import load_config, config_hash
from patchloss.cli import config_files
from patchloss.reporting.records import read_record, select_latest

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--input", type=Path, default=root / "runs")
parser.add_argument("--output", type=Path, default=root / "paper")
args = parser.parse_args()
expected = {c["experiment"]: config_hash(c) for c in (load_config(f) for f in config_files("full"))}
record = {}
candidates = []
for f in sorted(args.input.glob("*/metrics.json")):
    run, data = read_record(f.parent)
    if run["config_hash"] != expected.get(run["experiment_id"]):
        continue
    candidates.append(
        {
            "experiment_id": run["experiment_id"],
            "seed": run["seed"],
            "run_id": run["run_id"],
            "config_hash": run["config_hash"],
            "source_sha256": run.get("source_sha256", "legacy"),
        }
    )
    record[(run["experiment_id"], run["seed"])] = data
select_latest(pd.DataFrame(candidates))  # Reject mixed implementations before writing anything.
need = [
    ("E00", 0),
    ("E01", 0),
    ("E02", 0),
    ("E03", 0),
    ("E04", 0),
    ("E05", 0),
    ("E06", 0),
    ("E06", 1),
    ("E06", 2),
    ("E07", 0),
    ("E08", 0),
    ("E09", 0),
    ("E09", 1),
    ("E09", 2),
]
missing = [i for i in need if i not in record]
if missing:
    raise RuntimeError(f"Required measured records not present: {missing}")


def val(e, seed, key):
    return record[(e, seed)]["metrics"][key]


def fm(v, n=4):
    return f"{v:.{n}f}"


def scientific(v):
    mantissa, exponent = f"{v:.3e}".split("e")
    return rf"\ensuremath{{{mantissa}\times 10^{{{int(exponent)}}}}}"


learned = [val("E06", seed, "learned_accuracy") for seed in range(3)]
frozen = [val("E06", seed, "frozen_accuracy") for seed in range(3)]
macro = {
    "Roundtrip": fm(val("E00", 0, "max_abs_roundtrip"), 1),
    "CollisionResidual": scientific(val("E01", 0, "collision_residual_max")),
    "PairedChance": fm(val("E01", 0, "paired_probe_accuracy")),
    "MCMeanDeviation": fm(val("E02", 0, "mean_abs_mc_deviation")),
    "MCMaxDeviation": fm(val("E02", 0, "max_abs_mc_deviation")),
    "MCCells": str(val("E02", 0, "num_conditions")),
    "MCOutliers": str(val("E02", 0, "outside_nominal_95ci")),
    "NullChance": fm(val("E03", 0, "chance_error_null")),
    "RowRisk": fm(val("E03", 0, "full_signal_error")),
    "XORMlp": fm(val("E04", 0, "xor_mlp_accuracy")),
    "XORLinear": fm(val("E04", 0, "xor_linear_accuracy")),
    "MeanLearned": fm(np.mean(learned)),
    "MeanFrozen": fm(np.mean(frozen)),
    "MeanGain": fm(np.mean(np.array(learned) - np.array(frozen))),
    "LearnedStd": fm(np.std(learned, ddof=1)),
    "FrozenStd": fm(np.std(frozen, ddof=1)),
    "LowpassRaw": fm(val("E07", 0, "signal_raw_accuracy")),
    "LowpassSmoothed": fm(val("E07", 0, "signal_lowpass_accuracy")),
    "RankNoOverlap": str(val("E08", 0, "nonoverlap_rank")),
    "RankOverlap": str(val("E08", 0, "overlap_rank")),
}
tex = ["% AUTOGENERATED from actual completed run metrics; do not edit by hand."]
for k, v in macro.items():
    tex.append("\\newcommand{\\" + k + "}{" + v + "}")
tex.append(r"\begin{table}[t]")
tex.append(
    r"\centering\small\caption{Independent E06 seeds, held-out accuracy. Frozen and learned models begin from the same projection; this is a designed Gaussian task, not natural-image accuracy.}\label{tab:learned}"
)
tex.append(r"\begin{tabular}{rcc}\toprule Seed & Frozen & Learned\\\midrule")
for seed in range(3):
    tex.append(f"{seed} & {fm(frozen[seed])} & {fm(learned[seed])}" + r"\\")
tex.append(r"\midrule Mean & \MeanFrozen & \MeanLearned\\\bottomrule\end{tabular}\end{table}")
# E09 table: per seed results (classes)
tex.append(r"\begin{table}[t]")
tex.append(
    r"\centering\footnotesize\caption{Observed E09 held-out accuracy for three seeds. Models trained from scratch with six-epoch cap; failure to learn XOR is not proof of representation loss.}\label{tab:models}"
)
tex.append(r"\begin{tabular}{llccc}\toprule Task & Model & Seed 0 & Seed 1 & Seed 2\\\midrule")
for task in ("frequency", "relational"):
    for m in ("tiny_vit_frozen", "tiny_vit_learned", "cnn"):
        acc = []
        for seed in range(3):
            rows = record[("E09", seed)]["rows"]
            r = next(x for x in rows if x["task"] == task and x["model"] == m)
            acc.append(fm(r["accuracy"], 3))
        name = {"tiny_vit_frozen": "ViT fixed", "tiny_vit_learned": "ViT learned", "cnn": "CNN"}[m]
        tex.append(f"{task} & {name} & " + " & ".join(acc) + r"\\")
tex.append(r"\bottomrule\end{tabular}\end{table}")
pos = next(i for i, line in enumerate(tex) if line.startswith(r"\begin{table}"))
args.output.mkdir(parents=True, exist_ok=True)
(args.output / "results_generated.tex").write_text("\n".join(tex[:pos]) + "\n")
(args.output / "tables_generated.tex").write_text("\n".join(tex[pos:]) + "\n")
(args.output / "results_sources.json").write_text(json.dumps(candidates, indent=2) + "\n")
print("Generated LaTeX macros from", len(record), "unique (experiment, seed) combinations")
